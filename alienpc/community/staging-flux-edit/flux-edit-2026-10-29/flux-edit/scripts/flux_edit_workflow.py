def write_template(templates_root=TEMPLATES):
    d = os.path.join(templates_root, NAME, VERSION)
    os.makedirs(d, exist_ok=True)
    files = template_files()
    for fn, txt in files.items():
        with open(os.path.join(d, fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)
    idx = {"templates": [{"name": NAME, "version": VERSION, "phase": "A", "status": "draft",
                          "description": "BFS head swap, Klein 9B, flattened core nodes",
                          "source": "plans/bfs-head-swap-klein-2026-10-26.md §0",
                          "files": {fn: hashlib.sha256(t.encode()).hexdigest() for fn, t in sorted(files.items())}}]}
    with open(os.path.join(templates_root, "index.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(_dump(idx))


