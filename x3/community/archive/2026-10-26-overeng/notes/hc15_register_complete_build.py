def ck_scope(rows, docs=None):
    """A row set must cover the current scope exactly once, and a paid clip whose graph is gone is an
    unattributable render (the item's own words: name the graph). `docs` is unused; the signature is shared
    by every gate so the seeded probes call them uniformly (L10)."""
    ids = current_ids()
    got = [r["_id"] for r in rows]
    out = []
    for nid in ids:
        if nid not in got:
            out.append(f"SCOPE-MISS {nid}: no measured row for a graph in p7/graphs")
    for nid in set(got):
        if got.count(nid) > 1:
            out.append(f"SCOPE-DUP {nid}: measured twice")
    for r in rows:
        if r["mp4"] != "ABSENT" and r["graph"].startswith("ABSENT"):
            out.append(f"SCOPE-ORPHAN {r['_id']}: a clip of {r['mp4_bytes']} B on disk with no graph in "
                       "p7/graphs - the row cannot name the graph that made it, so the render is unattributable")
    return out


def ck_coverage(rows, docs):
    """The register carries exactly one generated row per clip in scope (the item's done-when)."""
    parsed = parse(docs[DOC_MAIN])
    out = []
    for r in rows:
        nid = r["_id"]
        n = len(parsed.get(nid, []))
        if n == 0:
            out.append(f"COVERAGE-MISS {nid}: the register names no generated row for it (L8: runs/ is "
                       "gitignored, so an unregistered paid clip has no durable proof)")
        elif n > 1:
            out.append(f"COVERAGE-DUP {nid}: {n} generated rows - one clip must have one row")
    for nid in parsed:
        if nid not in {r["_id"] for r in rows}:
            out.append(f"COVERAGE-EXTRA {nid}: the register rows a clip that is not in scope (no graph in "
                       "p7/graphs, or a removed run) - a row must be regenerable from disk")
    return out


def ck_drift(rows, docs):
    """Every field in the generated text must equal a fresh measurement (the 0.4 anti-drift rule, applied to
    the complete register). A hand-edit here is a claim the disk does not support."""
    parsed = parse(docs[DOC_MAIN])
    out = []
    for r in rows:
        c = (parsed.get(r["_id"]) or [None])[0]
        if not c:
            continue
        miss = [k for k in KEYS if k not in c or k not in r]
        if miss:
            out.append(f"ROW-DRIFT-FIELD {r['_id']}: the row omits {miss} - a row that omits the graph bytes "
                       "or the prompt keys is not a receipt of that render")
            continue
        bad = [k for k in KEYS if c[k] != str(r[k])]
        if bad:
            out.append(f"ROW-DRIFT {r['_id']}: the note disagrees with the disk on {bad[:4]} - the doc says "
                       + "; ".join(f"{k}={c[k][:40]!r} disk={str(r[k])[:40]!r}" for k in bad[:2]))
    return out


def ck_names(rows, docs=None):
    """The item's title rule, measured: a row names the graph that made the clip (path opens, sha matches),
    the clip's own bytes/sha256, and the prompt keys of that graph re-derived from the file it names."""
    out = []
    for r in rows:
        nid = r["_id"]
        gp = "" if str(r["graph"]).startswith("ABSENT") else os.path.join(W, r["graph"])
        if not gp or not os.path.isfile(gp):
            out.append(f"NAMES-GRAPH {nid}: graph {r['graph']!r} is not a file - every render row must name "
                       "the graph that made the clip")
            continue
        if sha(gp) != r["graph_sha256"]:
            out.append(f"NAMES-GRAPH-SHA {nid}: the graph at {r['graph']} measures {sha(gp)[:16]}, the row "
                       f"claims {r['graph_sha256'][:16]}")
        if int(os.path.getsize(gp)) != int(r["graph_bytes"]):
            out.append(f"NAMES-GRAPH-BYTES {nid}: graph measures {os.path.getsize(gp)} B, row says {r['graph_bytes']}")
        if r["mp4"] != "ABSENT":
            mp4 = os.path.join(W, r["mp4"])
            if not os.path.isfile(mp4):
                out.append(f"NAMES-MP4 {nid}: the row names {r['mp4']!r}, which is not a file")
            else:
                if os.path.getsize(mp4) != int(r["mp4_bytes"]):
                    out.append(f"NAMES-BYTES {nid}: the mp4 measures {os.path.getsize(mp4)} B, the row claims "
                               f"{r['mp4_bytes']}")
                if sha(mp4) != r["mp4_sha256"]:
                    out.append(f"NAMES-SHA {nid}: the mp4 measures sha {sha(mp4)[:16]}, the row claims "
                               f"{r['mp4_sha256'][:16]}")
        fresh = AC.rl_census_at(gp)
        claimed = AC.rl_parse_keys(r.get("prompt_keys"))
        if not fresh and not claimed:
            out.append(f"NAMES-KEYS {nid}: the graph named by the row carries 0 prompt-bearing keys, and the row "
                       "says the same - a render with no prose to gate is not a clip of this pipeline")
        elif claimed != fresh:
            out.append(f"NAMES-KEYS {nid}: prompt_keys {sorted(claimed.items())} != the graph's "
                       f"{sorted(fresh.items())} measured off {r['graph']} (L11: the keys are the claim)")
        if sum(claimed.values()) != int(r["prompt_strings"]):
            out.append(f"NAMES-KEYS-SUM {nid}: prompt_keys sums to {sum(claimed.values())} and prompt_strings "
                       f"says {r['prompt_strings']}")
    return out


def ck_state(rows, docs):
    """A state is a classification of files: three pieces = paid, render evidence without the clip =
    half-paid, a graph with no render evidence = staged. A non-paid row may not carry clip numbers."""
    out = []
    for r in rows:
        nid = r["_id"]
        st = state_of(r)
        if st != r["state"]:
            out.append(f"STATE-DRIFT {nid}: disk says {st}, the row says {r['state']}")
        if r["mp4"] == "ABSENT":
            nums = [k for k in ("mp4_bytes", "mp4_sha256") if str(r.get(k)) != "ABSENT"]
            if nums:
                out.append(f"STATE-CLAIM {nid}: the row states no clip on disk while it carries {nums} - a "
                           "half-paid run is not a paid clip (L20)")
        elif not has_clip(r) and r["state"] == "paid":
            out.append(f"STATE-CLAIM {nid}: state paid with no mp4 file at {r['mp4']} (L20)")
        if not re.match(r"^\d/3 pieces: ", str(r.get("pieces", ""))):
            out.append(f"STATE-PIECES {nid}: the pieces field {str(r.get('pieces'))[:40]!r} is not a /3 count "
                       "- a state with no stated evidence is a claim (L20)")
    return out


def units(text):
    """Headings and table rows as separable units, so the family-register rule reads a row, not a whole doc."""
    u, cur = [], []
    for ln in text.splitlines():
        if re.match(r"^#{2,4} ", ln) or ln.startswith("|"):
            if cur:
                u.append("\n".join(cur))
            cur = [ln] if ln.startswith("|") else []
        else:
            cur.append(ln)
    if cur:
        u.append("\n".join(cur))
    return u


def ck_family_register(rows, docs):
    """A clip owned by another register (the two 5 s clips live in the top5 record) must be attributable
    there: the id, the graph path, the full mp4 sha256 and the graph sha256 in the doc, and the prompt keys
    named in the same unit as the id. Doc-level for the hashes (the E5 record states them in its proof
    table), unit-level for the prompt keys - and that weakness is written into the record, not hidden."""
    out = []
    for r in rows:
        doc = r["register_doc"]
        if doc == DOC_MAIN or doc not in docs:
            continue
        txt = docs[doc]
        nid = r["_id"]
        if nid not in txt:
            out.append(f"FAM-REGISTER {nid}: not named in its own register {os.path.basename(doc)}")
            continue
        for want, code in ((f"p7/graphs/{nid}.api.json", "FAM-NAME-GRAPH"),
                           (r["mp4_sha256"], "FAM-NAME-MP4-SHA"),
                           (r["graph_sha256"], "FAM-NAME-GRAPH-SHA")):
            if want not in txt:
                out.append(f"{code} {nid}: {os.path.basename(doc)} carries no {want[:24]}... - a register row "
                           "that omits it is not a receipt")
        key_named = False
        kp = re.compile(r"\b[a-z0-9_]+\.[a-z0-9_.]*prompt\b", re.I)
        for u in units(txt):
            if nid in u and kp.search(u):
                key_named = True
                break
        if not key_named:
            out.append(f"FAM-NAME-PROMPT-KEYS {nid}: no unit naming the id names a prompt key - the adults "
                       "gate's reach is unrecorded (L11)")
    return out


def ck_registered_text(rows, docs):
    """The done-when as a rule over the doc's text: `git grep -c s51150032 -- notes/hc15_20261024.md`
    prints >= 1, and the same for every paid clip's own id in the register that owns it."""
    out = []
    for r in rows:
        doc = r["register_doc"]
        if doc not in docs:
            continue
        if r["_id"] not in docs[doc]:
            out.append(f"NOT-REGISTERED {r['_id']}: the register text never names this id")
    return out


def ck_legacy(legacy, corpus):
    """Legacy clips have no graph to name, so the rule for them is attribution: the id appears in a tracked
    file under notes/. Named by the gate, never silently dropped."""
    out = []
    present = set(re.findall("|".join(re.escape(x) for x in legacy), corpus)) if legacy else set()
    for nid in legacy:
        if nid not in present:
            out.append(f"LEGACY-UNNAMED {nid}: a rendered clip in runs/ whose id appears in no tracked file "
                       "under notes/ - it has no register row and no graph, so nothing names it")
    return out


def run_gates(rows, docs):
    legacy = legacy_ids()
    return (ck_scope(rows) + ck_coverage(rows, docs) + ck_drift(rows, docs) + ck_names(rows)
            + ck_state(rows, docs) + ck_family_register(rows, docs) + ck_registered_text(rows, docs)
            + ck_legacy(legacy, tracked_corpus()))


