def selftest():
    t0 = time.time()
    rows = measure_all()
    docs = read_docs()
    corpus = tracked_corpus()
    leg = legacy_ids()
    if not leg:
        print("SELFTEST ABORT: no legacy render in runs/ - the attribution rule has nothing to seed, so it "
              "cannot be called a gate today")
        return 1
    victim = leg[0]
    real = run_gates(rows, docs)
    seeds = []
    by = {r["_id"]: r for r in rows}
    keep = "ali163_hc15_gi046_s51150032"          # the clip the plan row names
    paid = [r for r in rows if r["state"] == "paid"][0]

    def seeded(label, det, fn, mutate):
        d = copy.deepcopy(rows)
        dd = {k: v for k, v in docs.items()}
        changed = mutate(d, dd)
        if not changed:
            print(f"SEED NO-OP {label}: the mutation changed nothing - the seed proves nothing (L10/E5)")
            return None
        fires = fn(d, dd)
        seeds.append((label, det, fires))
        return fires

    def drop_row(d, dd):
        return bool([r for r in d if r["_id"] == keep]) and d.remove(next(r for r in d if r["_id"] == keep)) or True

    def dup_row(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        d.append(copy.deepcopy(r))
        return True

    def extra_row(d, dd):
        r = copy.deepcopy(next(x for x in d if x["_id"] == keep))
        r["_id"] = "not_a_clip_on_disk_zz"
        d.append(r)
        return True

    def drop_from_doc(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        head = f"#### Clip {r['_n']} - {r['_id']}"
        dd[DOC_MAIN] = dd[DOC_MAIN].replace(head, "#### Clip 99 - removed_zz", 1)
        return head not in dd[DOC_MAIN]

    def dup_in_doc(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        head = f"#### Clip {r['_n']} - {r['_id']} ({r['_scene']}, {r['state']})"
        parts = dd[DOC_MAIN].split(head)
        if len(parts) < 2:
            return False
        blk = parts[1].split("#### Clip")[0]
        dd[DOC_MAIN] = dd[DOC_MAIN].replace(END, head + "\n" + blk, 1)
        return dd[DOC_MAIN].count(head) == 2

    def doc_sha(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        old = dd[DOC_MAIN]
        dd[DOC_MAIN] = old.replace(r["mp4_sha256"], "0" * 64)
        return dd[DOC_MAIN] != old

    def doc_graph(d, dd):
        dd[DOC_MAIN] = dd[DOC_MAIN].replace(f"p7/graphs/{keep}.api.json", "p7/graphs/gone_zz.api.json")
        return True

    def doc_state(d, dd):
        r = next((x for x in d if x["state"].startswith("half-paid")), None)
        if not r:
            return False
        dd[DOC_MAIN] = dd[DOC_MAIN].replace(f"- state: {r['state']}", "- state: paid", 1)
        return "- state: paid" in dd[DOC_MAIN] and f"- state: {r['state']}" not in dd[DOC_MAIN]

    def row_state(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        r["state"] = "staged (graph exists, no render evidence on disk)"
        return True

    def row_sha(d, dd):
        next(x for x in d if x["_id"] == keep)["mp4_sha256"] = "0" * 64
        return True

    def row_bytes(d, dd):
        next(x for x in d if x["_id"] == keep)["mp4_bytes"] = "1"
        return True

    def row_graph_absent(d, dd):
        next(x for x in d if x["_id"] == keep)["graph"] = "ABSENT"
        return True

    def row_graph_sha(d, dd):
        next(x for x in d if x["_id"] == keep)["graph_sha256"] = "0" * 64
        return True

    def row_keys_dropped(d, dd):
        next(x for x in d if x["_id"] == keep)["prompt_keys"] = "NO PROMPT-BEARING KEY"
        return True

    def row_keys_count(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        c = AC.rl_parse_keys(r["prompt_keys"])
        k = sorted(c)[0]
        c[k] += 1
        r["prompt_keys"] = AC.rl_fmt_keys(c)
        return True

    def row_keys_shifted(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        c = AC.rl_parse_keys(r["prompt_keys"])
        k = sorted(c)[0]
        del c[k]
        c[k + "_zz"] = 1
        r["prompt_keys"] = AC.rl_fmt_keys(c)
        return True

    def row_field_missing(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        del r["comfy_output"]
        r["_id"] = keep
        return True

    def row_halfpaid_claim(d, dd):
        r = next(x for x in d if x["_id"] == keep)
        r["mp4"] = "ABSENT"
        r["comfy_output"] = "no ComfyUI output video"
        return True

    def pieces_unformatted(d, dd):
        next(x for x in d if x["_id"] == keep)["pieces"] = "the three files are there"
        return True

    def top5_graph(d, dd):
        dd[DOC_TOP5] = dd[DOC_TOP5].replace("p7/graphs/ali163_top5_gi046_s51160001.api.json", "gone_zz")
        return True

    def top5_sha(d, dd):
        t = next(x for x in d if x["_id"] == "ali163_top5_gi046_s51160001")
        dd[DOC_TOP5] = dd[DOC_TOP5].replace(t["mp4_sha256"], "0" * 64)
        return True

    def top5_prompt(d, dd):
        dd[DOC_TOP5] = re.sub(r"c0\.prompt", "the prompt text", dd[DOC_TOP5])
        dd[DOC_TOP5] = re.sub(r"c0\.inputs\.prompt", "the prompt text", dd[DOC_TOP5])
        return True

    def legacy_gate(d, dd):
        return ck_legacy([victim], corpus.replace(victim, "redacted_zz"))

    def legacy_unnamed(d, dd):
        return corpus.count(victim) >= 1 and victim not in corpus.replace(victim, "redacted_zz")

    def not_registered(d, dd):
        dd[DOC_MAIN] = dd[DOC_MAIN].replace(keep, "redacted_zz")
        return True

    cases = [
        ("a paid clip's row is dropped from the row set", "ck_coverage", ck_coverage, drop_row),
        ("a row is measured twice (the same clip rowed twice)", "ck_scope", ck_scope, dup_row),
        ("a row for a clip that is not in scope", "ck_coverage", ck_coverage, extra_row),
        ("the generated block lost one clip's row", "ck_coverage", ck_coverage, drop_from_doc),
        ("the generated block carries the same clip twice", "ck_coverage", ck_coverage, dup_in_doc),
        ("the note's mp4 sha256 is not the file's", "ck_drift", ck_drift, doc_sha),
        ("the note names a graph path that does not exist", "ck_drift", ck_drift, doc_graph),
        ("the note calls a half-paid run `paid`", "ck_drift", ck_drift, doc_state),
        ("the row's own state disagrees with the disk", "ck_state", ck_state, row_state),
        ("the row's mp4 sha256 is not the file's", "ck_names", ck_names, row_sha),
        ("the row's mp4 bytes are not the file's", "ck_names", ck_names, row_bytes),
        ("a paid clip has no graph to name", "ck_scope", ck_scope, row_graph_absent),
        ("the row's graph sha256 is not the file it names", "ck_names", ck_names, row_graph_sha),
        ("the row names 0 prompt keys (L11)", "ck_names", ck_names, row_keys_dropped),
        ("the row's prompt key counts do not sum to prompt_strings", "ck_names", ck_names, row_keys_count),
        ("the row names a key the graph does not carry", "ck_names", ck_names, row_keys_shifted),
        ("a row omits a field", "ck_drift", ck_drift, row_field_missing),
        ("a non-paid row carries clip fields (half-paid read as paid)", "ck_state", ck_state, row_halfpaid_claim),
        ("a row states a state with no /3 evidence count", "ck_state", ck_state, pieces_unformatted),
        ("the top5 register omits the graph path of its clip", "ck_family_register", ck_family_register, top5_graph),
        ("the top5 register omits its clip's mp4 sha256", "ck_family_register", ck_family_register, top5_sha),
        ("the top5 register names no prompt key with its id", "ck_family_register", ck_family_register, top5_prompt),
        ("a legacy clip's id appears in no tracked note", "ck_legacy", legacy_gate, legacy_unnamed),
        ("the register never names a paid clip's id (the 2.4b done-when)", "ck_registered_text",
         ck_registered_text, not_registered),
    ]
    silent = []
    for label, det, fn, mut in cases:
        got = seeded(label, det, fn, mut)
        if got is None:
            return 1
        if not got:
            silent.append(label)
    fires = run_gates(rows, docs)
    ok = not silent and not fires and len(seeds) == len(cases)
    for label, det, got in seeds:
        print(("SEED FIRED " if got else "SEED MISSED ") + f"{label} -> {det}: {str(got)[:110]}")
    print(f"control real artifact: {len(fires)} findings " + (str(fires)[:200] if fires else "(clean)"))
    print(f"{SELFTEST_CLEAN} seeds={len(seeds)} fired={len(seeds) - len(silent)} silent={len(silent)} "
          f"real_findings={len(fires)} in {time.time() - t0:.1f} s" if ok else
          f"{SELFTEST_RED} silent={len(silent)} {silent[:3]} real_findings={len(fires)}")
    return 0 if ok else 1


