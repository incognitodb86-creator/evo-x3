def has_clip(r):
    return r["mp4"] != "ABSENT" and os.path.isfile(os.path.join(W, r["mp4"]))


def state_of(r):
    """Four states, all read off files: paid = the three pieces + an ok=True objective + a server-side output
    video; stalled-collected = the clip IS on disk while objective.json records no ok=True attempt (measured:
    runs/ali163_hc15_bd002_s51150021/ carries a 6,297,740 B mp4 with an objective.json whose attempts list is
    empty - L19: a client stall is not an objective failure, the clip is collected and never re-rendered);
    half-paid = render evidence with NO clip on disk (measured: runs/ali163_hc15_gi046_s51150031/ has
    objective.json + status.log and no mp4); staged = a graph with no render evidence. A state is derived from
    files, never from a claim, and never from a missing client receipt alone."""
    if has_clip(r) and r["objective_json"].startswith("ok=True") \
            and not r["render_start_ct"].startswith("NO JOB START") and not r["comfy_output"].startswith("no ComfyUI"):
        return "paid"
    if has_clip(r) and not r["objective_json"].startswith("ok=True"):
        return ("clip on disk, client-stalled (objective.json records no ok=True attempt) - collected from "
                "disk, never re-rendered (L19)")
    if not has_clip(r) and not r["render_start_ct"].startswith("NO JOB START"):
        return "half-paid (render evidence, no clip on disk)"
    return "staged (graph exists, no render evidence on disk)"


def parse(text):
    """My generated block back out of the markdown, id -> list of field dicts (a duplicate is a finding, so
    the list is never collapsed). The heading is `#### Clip`, which AC.rl_parse's `^### Clip` never matches."""
    out, cur = {}, None
    inside = False
    for ln in text.splitlines():
        if ln.startswith(BEG):
            inside = True
            continue
        if ln.startswith(END):
            break
        if not inside:
            continue
        m = re.match(r"^#### Clip \d+ - (\S+) ", ln)
        if m:
            cur = m.group(1)
            out.setdefault(cur, []).append({})
            continue
        m = re.match(r"^- ([a-z0-9_]+): (.*)$", ln)
        if m and cur:
            out[cur][-1][m.group(1)] = m.group(2)
    return out


def block(rows):
    L = [HEAD, "", BEG, "",
         "Generated by `notes/hc15_register_complete_build.py --emit` from the files on disk (fix_plan 2.4b).",
         "`--check` re-measures every field of every row and fails on drift; `--selftest` seeds each fault and",
         "requires its detector to fire there and 0 here (L10). Scope: every id with a graph in p7/graphs, in",
         "every state the disk shows - `paid`; a clip on disk whose `objective.json` records no ok=True",
         "attempt (a client stall: collected, never re-rendered, L19); `half-paid` (render evidence, no clip);",
         "`staged` (graph, no render). Each row names the graph path + sha256, the mp4 bytes + sha256, and the",
         "prompt keys the adults gate saw (L11: the keys, not only a count). Legacy clips (no graph in p7/graphs) are not",
         "rowed here; their rule is attribution by id, which `--check` measures over the tracked notes.",
         "No keep, no ranking, no quality claim - KEEP is Derrick's alone. Nothing here re-renders (L19).", "",
         "| # | clip | state | ffprobe | audio | render min | graph | mp4 bytes | mp4 sha256 | prompt keys |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['_n']} | {r['_id']} | {r['state']} | {r['ffprobe']} | {r['audio']} | {r['render_min']} "
                 f"| `{r['graph']}` | {r['mp4_bytes']} | `{r['mp4_sha256']}` | {r['prompt_keys']} |")
    L += ["", "The table is the short form; the row is the key list below it. `p7/jobs/<id>.result.json` is not",
          "written by this render path (L20), so a row plus the runs logs are the durable proof.", ""]
    for r in rows:
        L.append(f"#### Clip {r['_n']} - {r['_id']} ({r['_scene']}, {r['state']})")
        for k in KEYS:
            L.append(f"- {k}: {r[k]}")
        L.append("")
    L.append(END)
    return "\n".join(L) + "\n"


def emit():
    rows = measure_all()
    doc = open(DOC_MAIN, encoding="utf-8").read()
    blk = block(rows)
    if BEG in doc and END in doc:
        pre = doc.split(BEG, 1)[0].rstrip() + "\n\n"
        post = doc.split(END, 1)[1]
        new = pre + blk + post
    elif HEAD in doc:
        new = doc.rstrip("\r\n") + "\n\n" + blk + "\n"
    else:
        new = doc.rstrip("\r\n") + "\n\n" + blk + "\n"
    open(DOC_MAIN, "w", encoding="utf-8", newline="").write(new)
    docs = read_docs()
    fires = run_gates(rows, docs)
    print(f"wrote {rel(DOC_MAIN)}: block {len(blk)} B, {len(rows)} rows; "
          + (f"{len(fires)} findings" if fires else "gates clean"))
    for f in fires:
        print("  FAIL", f)
    return 1 if fires else 0


